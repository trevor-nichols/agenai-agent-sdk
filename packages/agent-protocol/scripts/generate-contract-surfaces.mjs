function header(fileName, purpose) {
  return [
    '// ------------------------------------------------------------------------------------------------',
    `//                ${fileName} - ${purpose}`,
    '// ------------------------------------------------------------------------------------------------',
    '',
    '// This file is generated by scripts/generate-contract-surfaces.mjs. Do not edit by hand.',
    '',
  ].join('\n');
}

function writeGenerated(relativePath, source) {
  const targetPath = resolve(sourceRoot, relativePath);
  const content = source.endsWith('\n') ? source : `${source}\n`;
  let existing = null;
  try {
    existing = readFileSync(targetPath, 'utf8');
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  if (existing === content) return;
  if (checkOnly) {
    throw new Error(`Generated protocol surface is stale: ${relativePath}`);
  }
  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, content);
}

// ------------------------------------------------------------------------------------------------
//                Plain Public Barrels
// ------------------------------------------------------------------------------------------------

for (const [relativePath, modules] of Object.entries(publicSurfaces)) {
  writeGenerated(
    relativePath,
    [
      header(relativePath.split('/').at(-1), 'Plain agent protocol exports'),
      ...modules.map((module) => `export * from '${module}';`),
      '',
    ].join('\n'),
  );
}

// ------------------------------------------------------------------------------------------------
//                Schema-to-Plain-Type Equality Proof
// ------------------------------------------------------------------------------------------------

const typesByModule = new Map();
const schemasByModule = new Map();
for (const [typeName, schemaName, moduleName] of equalityRecords) {
  typesByModule.set(moduleName, [...(typesByModule.get(moduleName) ?? []), typeName]);
  schemasByModule.set(moduleName, [...(schemasByModule.get(moduleName) ?? []), schemaName]);
}

const imports = ["import type { z } from 'zod/v4';", ''];
for (const [moduleName, typeNames] of [...typesByModule].sort()) {
  const plainModule = moduleName === 'foundation'
    ? '../foundation/types.js'
    : `../${moduleName}/types.js`;
  imports.push(
    `import type { ${typeNames.sort().join(', ')} } from '${plainModule}';`,
  );
}
for (const [moduleName, schemaNames] of [...schemasByModule].sort()) {
  imports.push(
    `import { ${schemaNames.sort().join(', ')} } from './${moduleName}.js';`,
  );
}

const assertions = equalityRecords.flatMap(([typeName, schemaName]) => [
  `  Assert<Extends<z.output<typeof ${schemaName}>, ${typeName}>>,`,
  `  Assert<Extends<${typeName}, z.output<typeof ${schemaName}>>>,`,
]);

writeGenerated(
  'zod/typeEquality.generated.ts',
  [
    header('typeEquality.generated.ts', 'Schema and plain type equality proof'),
    ...imports,
    '',
    'type Extends<Left, Right> = [Left] extends [Right] ? true : false;',
    'type Assert<Value extends true> = Value;',
    '',
    'export type AgentProtocolSchemaTypeAssertions = readonly [',
    ...assertions,
    '];',
    '',
  ].join('\n'),
);

process.stdout.write(
  `${checkOnly ? 'Checked' : 'Generated'} agent protocol contract surfaces.\n`,
);
